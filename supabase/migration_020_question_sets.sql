-- Migration 020: question sets with per-learner access
--  * public.question_sets: separate question banks ("USMF Final 2026", "obgyn 6th year", ...)
--  * public.set_access: which learners may use which sets (admins see every set)
--  * disciplines, categories, questions and sessions carry set_id; categories and
--    questions inherit it from their discipline / category automatically
--  * Learners can only read disciplines, topics and questions of their sets, and can only
--    answer questions and start tests in their sets
--  * Every existing user gets USMF Final 2026

create table if not exists public.question_sets (
  id          smallint generated by default as identity primary key,
  name        text not null unique check (char_length(trim(name)) between 2 and 60),
  description text check (char_length(description) <= 300),
  sort        int not null default 0,
  created_at  timestamptz not null default now()
);
insert into public.question_sets (id, name, sort) values (1, 'USMF Final 2026', 1) on conflict (id) do nothing;
select setval(pg_get_serial_sequence('public.question_sets', 'id'), greatest((select max(id) from public.question_sets), 1));

create table if not exists public.set_access (
  user_id    uuid not null references public.profiles (id) on delete cascade,
  set_id     smallint not null references public.question_sets (id) on delete cascade,
  granted_by uuid default auth.uid() references public.profiles (id) on delete set null,
  granted_at timestamptz not null default now(),
  primary key (user_id, set_id)
);
create index if not exists set_access_set_idx on public.set_access (set_id);
create index if not exists set_access_granted_by_idx on public.set_access (granted_by);
insert into public.set_access (user_id, set_id, granted_by) select id, 1, null from public.profiles on conflict do nothing;

-- set_id everywhere (existing rows belong to USMF Final 2026)
alter table public.disciplines add column if not exists set_id smallint not null default 1 references public.question_sets (id);
alter table public.categories  add column if not exists set_id smallint;
alter table public.questions   add column if not exists set_id smallint;
alter table public.sessions    add column if not exists set_id smallint not null default 1 references public.question_sets (id);
update public.categories c set set_id = d.set_id from public.disciplines d where d.id = c.discipline_id and c.set_id is distinct from d.set_id;
update public.categories set set_id = 1 where set_id is null;
alter table public.questions disable trigger questions_history;  -- not a content change, keep it out of question history
update public.questions q set set_id = c.set_id from public.categories c where c.id = q.category_id and q.set_id is distinct from c.set_id;
alter table public.questions enable trigger questions_history;
alter table public.categories alter column set_id set not null;
alter table public.questions  alter column set_id set not null;
create index if not exists disciplines_set_idx on public.disciplines (set_id);
create index if not exists categories_set_idx  on public.categories (set_id);
create index if not exists questions_set_idx   on public.questions (set_id, active);
create index if not exists sessions_set_idx    on public.sessions (user_id, set_id);

-- Names only need to be unique inside a set
alter table public.disciplines drop constraint if exists disciplines_name_key;
alter table public.categories  drop constraint if exists categories_name_key;
create unique index if not exists disciplines_set_name_key on public.disciplines (set_id, name);
create unique index if not exists categories_set_name_key  on public.categories (set_id, name);

-- Keep set_id in step
create or replace function private.category_set() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  new.set_id := coalesce((select set_id from public.disciplines where id = new.discipline_id), new.set_id, 1);
  return new;
end $$;
drop trigger if exists category_set on public.categories;
create trigger category_set before insert or update of discipline_id, set_id on public.categories
  for each row execute function private.category_set();

create or replace function private.question_set() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  new.set_id := (select set_id from public.categories where id = new.category_id);
  return new;
end $$;
drop trigger if exists question_set on public.questions;
create trigger question_set before insert or update of category_id, set_id on public.questions
  for each row execute function private.question_set();

create or replace function private.discipline_set_moved() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.categories set set_id = new.set_id where discipline_id = new.id;
  update public.questions q set set_id = new.set_id from public.categories c where c.id = q.category_id and c.discipline_id = new.id;
  return null;
end $$;
drop trigger if exists discipline_set_moved on public.disciplines;
create trigger discipline_set_moved after update of set_id on public.disciplines
  for each row when (old.set_id is distinct from new.set_id) execute function private.discipline_set_moved();
revoke all on function private.category_set(), private.question_set(), private.discipline_set_moved() from public, anon, authenticated;

-- The sets the signed-in user may use (admins: all)
create or replace function private.my_sets() returns smallint[]
language sql stable security definer set search_path = public as $$
  select case when private.is_admin() then (select coalesce(array_agg(id), '{}') from public.question_sets)
              else (select coalesce(array_agg(set_id), '{}') from public.set_access where user_id = auth.uid()) end;
$$;
revoke all on function private.my_sets() from public, anon;
grant execute on function private.my_sets() to authenticated;


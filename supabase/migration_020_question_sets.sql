-- Tests: start only in a set you have; answer only questions of your sets
drop function if exists public.start_session(text, text, integer);
create or replace function public.start_session(p_mode text, p_label text, p_total integer, p_set smallint default 1)
 returns bigint language plpgsql security definer set search_path to 'public'
as $function$
declare v_id bigint; v_unread int;
begin
  if auth.uid() is null then raise exception 'Not signed in'; end if;
  if not private.is_active() then raise exception 'Account is not active'; end if;
  if not (coalesce(p_set, 1) = any (private.my_sets())) then raise exception 'You don''t have access to this question set.'; end if;
  if not exists (select 1 from public.profiles where id = auth.uid() and role = 'admin') then
    v_unread := private.unread_notices(auth.uid());
    if v_unread > 0 then
      raise exception 'Please read and acknowledge the % new notice(s) first. Open the bell at the top and press Got it.', v_unread
        using errcode = 'P0001', hint = 'unread_notices';
    end if;
  end if;
  insert into public.sessions (user_id, mode, label, total, set_id)
  values (auth.uid(), p_mode, left(p_label, 200), greatest(p_total, 0), coalesce(p_set, 1))
  returning id into v_id;
  return v_id;
end;
$function$;
grant execute on function public.start_session(text, text, integer, smallint) to authenticated;

create or replace function public.record_answer(p_question_id bigint, p_selected integer[], p_session_id bigint default null::bigint)
 returns boolean language plpgsql security definer set search_path to 'public'
as $function$
declare
  v_key   int[];
  v_sel   int[];
  v_ok    boolean;
  v_box   int;
  v_days  int[] := array[0, 1, 3, 7, 14, 30];
  v_type  text;
  v_mode  text;
  v_mark  numeric;
  v_set   smallint;
begin
  if auth.uid() is null then raise exception 'Not signed in'; end if;
  if not private.is_active() then raise exception 'Account is not active'; end if;

  select array(select x from unnest(coalesce(correct, array[correct_index])) x order by x), qtype, set_id
    into v_key, v_type, v_set
  from public.questions where id = p_question_id;
  if v_key is null then raise exception 'Question not found'; end if;
  if not (v_set = any (private.my_sets())) then raise exception 'Question not found'; end if;
  v_sel := array(select distinct x from unnest(coalesce(p_selected, '{}')) x order by x);
  v_ok := v_sel = v_key;

  select case when v_ok then least(coalesce(p.box, 0) + 1, 5) else 0 end into v_box
  from (select 1) d
  left join public.progress p on p.user_id = auth.uid() and p.question_id = p_question_id;

  insert into public.progress as p
    (user_id, question_id, attempts, correct, last_correct, box, due_at, last_answered_at)
  values
    (auth.uid(), p_question_id, 1, case when v_ok then 1 else 0 end, v_ok, v_box,
     now() + make_interval(days => v_days[v_box + 1]), now())
  on conflict (user_id, question_id) do update set
    attempts         = p.attempts + 1,
    correct          = p.correct + case when v_ok then 1 else 0 end,
    last_correct     = v_ok,
    box              = v_box,
    due_at           = now() + make_interval(days => v_days[v_box + 1]),
    last_answered_at = now();

  if p_session_id is not null then
    select mode into v_mode from public.sessions where id = p_session_id and user_id = auth.uid();
    if not found then raise exception 'Session not found'; end if;

    if v_mode = 'mock' then
      if v_type = 'CM' then
        v_mark := ((select count(*) from unnest(v_sel) s where s = any(v_key))
                 - (select count(*) from unnest(v_sel) s where not (s = any(v_key))))::numeric
                 / greatest(cardinality(v_key), 1);
      else
        v_mark := case when v_ok then 1 else 0 end;
      end if;
    end if;

    insert into public.answers (user_id, session_id, question_id, selected, is_correct, mark)
    values (auth.uid(), p_session_id, p_question_id, v_sel, v_ok, v_mark);
    update public.sessions
       set answered = answered + 1,
           correct  = correct + case when v_ok then 1 else 0 end,
           points   = case when v_mode = 'mock' then coalesce(points, 0) + v_mark else points end
     where id = p_session_id;
  else
    insert into public.answers (user_id, question_id, selected, is_correct)
    values (auth.uid(), p_question_id, v_sel, v_ok);
  end if;

  return v_ok;
end;
$function$;

-- "Most missed by the group": only questions of the caller's sets, optionally one set
drop function if exists public.most_missed_ids(integer);
create or replace function public.most_missed_ids(p_limit integer default 20, p_set smallint default null)
 returns setof bigint language sql stable security definer set search_path to 'public'
as $function$
  with first_try as (
    select distinct on (a.user_id, a.question_id) a.question_id, a.is_correct
    from public.answers a order by a.user_id, a.question_id, a.answered_at
  )
  select f.question_id from first_try f
  join public.questions q on q.id = f.question_id and q.active
   and q.set_id = any (private.my_sets()) and (p_set is null or q.set_id = p_set)
  where private.is_active()
  group by f.question_id having count(*) >= 3 and count(*) filter (where not f.is_correct) > 0
  order by count(*) filter (where not f.is_correct)::numeric / count(*) desc, count(*) desc, f.question_id
  limit least(greatest(p_limit, 1), 50);
$function$;
revoke all on function public.most_missed_ids(integer, smallint) from public, anon;
grant execute on function public.most_missed_ids(integer, smallint) to authenticated;

drop function if exists public.admin_most_missed(integer, integer);
create or replace function public.admin_most_missed(p_limit integer default 20, p_min integer default 3, p_set smallint default null)
 returns table(question_id bigint, learners integer, wrong integer, wrong_pct integer, common_wrong integer[], common_wrong_n integer)
 language plpgsql stable set search_path to 'public'
as $function$
begin
  if not private.is_admin() then raise exception 'Admins only'; end if;
  return query
  with first_try as (
    select distinct on (a.user_id, a.question_id) a.user_id, a.question_id, a.selected, a.is_correct
    from public.answers a order by a.user_id, a.question_id, a.answered_at
  ), agg as (
    select f.question_id, count(*)::int n, count(*) filter (where not f.is_correct)::int w
    from first_try f join public.questions q on q.id = f.question_id and (p_set is null or q.set_id = p_set)
    group by f.question_id having count(*) >= p_min
  ), picks as (
    select f.question_id, f.selected, count(*)::int c,
           row_number() over (partition by f.question_id order by count(*) desc) rn
    from first_try f where not f.is_correct group by f.question_id, f.selected
  )
  select g.question_id, g.n, g.w, round(100.0 * g.w / g.n)::int, p.selected, coalesce(p.c, 0)
  from agg g left join picks p on p.question_id = g.question_id and p.rn = 1
  where g.w > 0
  order by g.w::numeric / g.n desc, g.n desc, g.question_id
  limit least(greatest(p_limit, 1), 100);
end $function$;
revoke all on function public.admin_most_missed(integer, integer, smallint) from public, anon;
grant execute on function public.admin_most_missed(integer, integer, smallint) to authenticated;

-- Audit: who was given or lost access to a set
create or replace function private.audit_set_access() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then return null; end if;
  if tg_op = 'INSERT' then
    perform private.audit('set.grant', new.user_id::text, jsonb_build_object('set', (select name from public.question_sets where id = new.set_id)));
  else
    perform private.audit('set.revoke', old.user_id::text, jsonb_build_object('set', (select name from public.question_sets where id = old.set_id)));
  end if;
  return null;
end $$;
revoke all on function private.audit_set_access() from public, anon, authenticated;
drop trigger if exists audit_set_access on public.set_access;
create trigger audit_set_access after insert or delete on public.set_access
  for each row execute function private.audit_set_access();
